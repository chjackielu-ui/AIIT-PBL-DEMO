import assert from 'node:assert/strict'
import {client} from './lib/api-client.mjs'

const student = client(), peer = client(), teacher = client(), outsider = client()
await Promise.all([student('/login', {id:'s1'}), peer('/login', {id:'s2'}), teacher('/login', {id:'t1'}), outsider('/login', {id:'s6'})])
const act = (who, op, fields = {}, status) => who('/actions', {op, projectId:'p1', ...fields}, status)
const project = async () => (await student('/state')).projects.find(p => p.id === 'p1')
const notices = who => who('/notifications')
async function upload(name, content, folderId, category = '文档', status) {
  const form = new FormData()
  form.set('category', category)
  form.set('folderId', folderId)
  form.set('file', new Blob([content]), name)
  return student('/projects/p1/files', form, status)
}
const existing = await project()
assert(existing.files.length > 0 && existing.files.every(file => existing.folders.some(folder => folder.id === file.folderId)))
const {folderId: parent} = await act(student, 'createFolder', {name:'回归资料'})
const {folderId: child} = await act(peer, 'createFolder', {name:'需求文档', parentId:parent})
await act(peer, 'createFolder', {name:'需求文档', parentId:parent}, 400)
await act(outsider, 'createFolder', {name:'无权限'}, 403)
await upload('invalid.pdf', 'body', 'unknown', '文档', 404)

await act(peer, 'setNotificationPreference', {type:'fileUpload', enabled:false})
const pdf = await upload('preview.pdf', '%PDF-1.4\n%%EOF', child)
assert.equal(pdf.folderId, child)
assert.equal(await student(`/projects/p1/files/${pdf.id}/preview`), '%PDF-1.4\n%%EOF')
await outsider(`/projects/p1/files/${pdf.id}/preview`, undefined, 403)
assert(!(await notices(peer)).some(n => n.path.includes(pdf.id)))
assert((await notices(teacher)).some(n => n.type === 'fileUpload' && n.path.includes(pdf.id)))
await act(student, 'deleteFolder', {folderId:child}, 400)
await act(peer, 'moveFile', {fileId:pdf.id, folderId:''})
await act(student, 'deleteFolder', {folderId:child})
const afterMove = await project()
const moved = afterMove.files.find(f => f.id === pdf.id)
assert.equal(moved.folderId, '')
assert.equal(moved.userId, 's1')
assert.equal(moved.time, pdf.time)
assert.equal(moved.modifiedBy, 's2')
assert.equal(afterMove.folders.find(f => f.id === parent).modifiedBy, 's1')
const log = await peer('/library/activity?projectId=p1')
assert(log.entries.some(event => event.action === '上传资料' && event.itemId === pdf.id && event.userId === 's1'))
assert(log.entries.some(event => event.action === '移动资料' && event.itemId === pdf.id && event.userId === 's2'))
assert(log.entries.some(event => event.action === '删除文件夹' && event.itemId === child))
await outsider('/library/activity?projectId=p1', undefined, 403)
await peer('/library/activity?offset=-1', undefined, 400)

const privateUpload = new FormData()
privateUpload.append('file', new Blob(['private library fixture']), 'private-library.txt')
const privateFile = await student('/library/files', privateUpload)
await act(student, 'personalEdit', {fileId:privateFile.id, name:'renamed-private.txt', category:'文档'})
assert((await student('/library/activity')).entries.some(event => event.itemId === privateFile.id && event.action === '编辑资料'))
assert(!(await peer('/library/activity')).entries.some(event => event.itemId === privateFile.id))

await act(student, 'setStudentShortcuts', {items:['library','transcript','pending']})
await act(student, 'setStudentShortcuts', {items:['library','library']}, 400)
await act(student, 'setStudentShortcuts', {items:['unknown']}, 400)
await act(teacher, 'setStudentShortcuts', {items:['library']}, 403)
assert.deepEqual((await student('/state')).user.studentShortcuts, ['library','transcript','pending'])
assert.equal((await peer('/state')).users.find(user => user.id === 's1').studentShortcuts, undefined)

await act(peer, 'setNotificationPreference', {type:'mentionAll', enabled:false})
await act(teacher, 'message', {text:'@全体 第一条集体通知'})
assert(!(await notices(peer)).some(n => n.type === 'mentionAll'))
assert((await notices(student)).some(n => n.type === 'mentionAll' && n.path.includes('?message=')))
assert(!(await notices(outsider)).some(n => n.type === 'mentionAll'))
await act(peer, 'setNotificationPreference', {type:'mentionAll', enabled:true})
await act(peer, 'setDiscussionMute', {muted:true})
await act(teacher, 'message', {text:'@全体 免打扰期间'})
assert(!(await notices(peer)).some(n => n.type === 'mentionAll'))
await act(peer, 'setDiscussionMute', {muted:false})
await act(teacher, 'message', {text:'@全体 恢复通知'})
assert((await notices(peer)).some(n => n.type === 'mentionAll'))

await act(student, 'message', {text:'学生回复测试'})
const replyToId = (await project()).messages.at(-1).id
await act(student, 'setNotificationPreference', {type:'reply', enabled:false})
await act(teacher, 'message', {text:'回复关闭', replyToId})
assert(!(await notices(student)).some(n => n.text === '回复关闭'))
await act(student, 'setNotificationPreference', {type:'reply', enabled:true})
await act(teacher, 'message', {text:'回复开启', replyToId})
assert((await notices(student)).some(n => n.text === '回复开启' && n.type === 'reply'))
await act(student, 'setNotificationPreference', {type:'mentionMe', enabled:false})
await act(teacher, 'message', {text:'@林同学 个人提及关闭', mentionIds:['s1']})
assert(!(await notices(student)).some(n => n.text.includes('个人提及关闭')))
await act(peer, 'setNotificationPreference', {type:'codeUpdate', enabled:false})
const source = await upload('verify.js', 'export const value = 1', '', '代码')
assert(!(await notices(peer)).some(n => n.type === 'codeUpdate' && n.path.includes(source.id)))
assert((await notices(teacher)).some(n => n.type === 'codeUpdate' && n.path.includes(source.id)))
await act(peer, 'readNotices')
assert((await notices(peer)).every(n => n.read))
assert(!(await project()).activity.some(a => a.text === '发布项目讨论'))
assert(!(await teacher('/state')).users.find(u => u.id === 's2').notificationPreferences)
await act(student, 'setNotificationPreference', {type:'mentionMe', enabled:true})
console.log('PASS 资料目录、操作日志及权限、快捷导航校验、PDF 预览、通知设置和已读')
